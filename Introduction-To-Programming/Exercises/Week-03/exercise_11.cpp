// Да се напише булев израз, който приема естествено число 
// - година и има стойност истина, ако годината е високосна. 
// Упътване: Една година е високосна, 
// ако се дели на 4 и не се дели на 100 или ако се дели на 400.
#include <iostream>

int main() {
    int year = 0;
    std::cin >> year;
    bool predicate = ((year % 4 == 0) 
        && (year % 100 != 0)) || (year % 400 == 0);
    std::cout << predicate << std::endl;
    return 0;
}